  direct_supervisor TEXT NOT NULL DEFAULT '',
  salary TEXT NOT NULL DEFAULT '',
  contract_duration_months INTEGER NOT NULL DEFAULT 12,
  start_date DATE,
  outpatient_benefit TEXT NOT NULL DEFAULT 'Penusahaan memberikan bantuan biaya pengobatan rawat jalan sebesar Rp 3.500.000,-',
